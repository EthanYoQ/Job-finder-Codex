"""Repack the checked-in 96px logo tiles without changing their visible pixels.

Run manually with Python + Pillow when the logo source manifest changes.
The generated assets are committed; Node builds need no image dependency.
"""
import json
import math
from pathlib import Path
from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parent.parent
logos = json.loads((ROOT / "scripts/company-logo-sources.json").read_text())
columns, tile_size, gutter = 8, 96, 2
stride = tile_size + 2 * gutter
rows = math.ceil(len(logos) / columns)
sheet = Image.new("RGBA", (columns * stride, rows * stride))
positions = {}
for index, logo in enumerate(logos):
    tile = Image.open(ROOT / "public" / logo["source"].lstrip("/")).convert("RGBA")
    assert tile.size == (tile_size, tile_size), logo["id"]
    column, row = index % columns, index // columns
    sheet.paste(tile, (column * stride + gutter, row * stride + gutter))
    positions[logo["id"]] = [column, row]
# Transparent guard pixels prevent adjacent brands bleeding into each other at
# fractional CSS sizes and high-DPI display scales.
for column, row in positions.values():
    x, y = column * stride, row * stride
    for box in [(x, y, x + stride, y + gutter), (x, y + stride - gutter, x + stride, y + stride),
                (x, y, x + gutter, y + stride), (x + stride - gutter, y, x + stride, y + stride)]:
        assert sheet.crop(box).getchannel("A").getextrema() == (0, 0)
out = ROOT / "src/app/assets"
out.mkdir(exist_ok=True)
sheet.save(out / "company-logos.png", optimize=True)
sheet.save(out / "company-logos.webp", lossless=True, method=6, exact=True)
# Fully transparent RGB values have no visible meaning. Compare on the actual
# white logo background, including all antialiased/partly transparent pixels.
def on_white(image):
    return Image.alpha_composite(Image.new("RGBA", sheet.size, "white"), image.convert("RGBA")).convert("RGB")
assert ImageChops.difference(on_white(sheet), on_white(Image.open(out / "company-logos.webp"))).getbbox() is None
(out / "company-logos.ts").write_text("// Generated by scripts/build-company-logo-sprite.py.\nexport default " + json.dumps({"columns": columns, "rows": rows, "tileSize": tile_size, "gutter": gutter, "positions": positions}, indent=2) + " as const;\n")
print(json.dumps({"logos": len(logos), "webpBytes": (out / "company-logos.webp").stat().st_size, "pngBytes": (out / "company-logos.png").stat().st_size, "visiblePixelDifference": 0}))
